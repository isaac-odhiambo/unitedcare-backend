phone_validator = RegexValidator(
    regex=r"^(07|01)\d{8}$",
    message="Phone number must be a valid Kenyan number (07XXXXXXXX or 01XXXXXXXX).",
)


def _money(v) -> Decimal:
    try:
        return Decimal(str(v))
    except Exception:
        return Decimal("0.00")


# =========================================================
# Mpesa Config
# =========================================================
class MpesaConfigSerializer(serializers.ModelSerializer):
    """
    Central payment channel config serializer.

    Frontend should use this for:
    - paybill number
    - business number
    - till number
    - enable/disable flags

    Account references like mus12, saving23, grp9, loan35
    should still be generated by frontend/backend business logic.
    """

    class Meta:
        model = MpesaConfig
        fields = [
            "id",
            "name",
            "paybill_number",
            "business_number",
            "till_number",
            "is_active",
            "is_paybill_enabled",
            "is_till_enabled",
            "notes",
            "updated_at",
        ]
        read_only_fields = [
            "id",
            "updated_at",
        ]

    def validate_paybill_number(self, value):
        return (value or "").strip()

    def validate_business_number(self, value):
        return (value or "").strip()

    def validate_till_number(self, value):
        return (value or "").strip()

    def validate_name(self, value):
        value = (value or "").strip()
        if not value:
            raise serializers.ValidationError("Name is required.")
        return value


# =========================================================
# Fee Config
# =========================================================
class TransactionFeeConfigSerializer(serializers.ModelSerializer):
    class Meta:
        model = TransactionFeeConfig
        fields = [
            "id",
            "purpose",
            "fixed_fee",
            "percentage_fee",
            "is_active",
            "updated_at",
        ]
        read_only_fields = ["id", "updated_at"]

    def validate_fixed_fee(self, value):
        if value is None:
            return Decimal("0.00")
        if value < Decimal("0.00"):
            raise serializers.ValidationError("Fixed fee cannot be negative.")
        return value

    def validate_percentage_fee(self, value):
        if value is None:
            return Decimal("0.00")
        if value < Decimal("0.00"):
            raise serializers.ValidationError("Percentage fee cannot be negative.")
        if value > Decimal("100.00"):
            raise serializers.ValidationError("Percentage fee cannot exceed 100.")
        return value


